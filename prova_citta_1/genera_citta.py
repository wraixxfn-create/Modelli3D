def make_batch_set(
    mats: dict[str, bpy.types.Material],
    col: bpy.types.Collection,
    keys: tuple[str, ...],
) -> dict[str, Batch]:
    return {key: Batch("Geometria — " + key, mats[key], col) for key in keys}


def spans_outside(
    a: float, b: float, gaps: tuple[tuple[float, float], ...]
) -> list[tuple[float, float]]:
    """Tratti di [a, b] che restano fuori dagli intervalli `gaps`.

    Serve a interrompere cordoli e marciapiedi dove la strada incontra una
    rotatoria: l'anello è una superficie propria e i marciapiedi devono
    fermarsi sul cerchio, non attraversarlo come barriere sopraelevate.
    """
    cuts = [a]
    for g0, g1 in sorted(gaps):
        if g1 <= a or g0 >= b:
            continue
        cuts.append(max(a, g0))
        cuts.append(min(b, g1))
    cuts.append(b)
    return [(cuts[i], cuts[i + 1]) for i in range(0, len(cuts), 2)
            if cuts[i + 1] - cuts[i] > 0.05]


def add_road_h(
    B: dict[str, Batch],
    y: float,
    x0: float = -100,
    x1: float = 100,
    width: float = ROAD_WIDTH,
    sidewalk: bool = True,
    gaps: tuple[tuple[float, float], ...] = (),
) -> None:
    B["asphalt"].box(((x0 + x1) / 2, y, ROAD_Y_OFFSET), (x1 - x0, width, ROAD_HEIGHT))
    # Cordoli e marciapiedi su entrambi i lati.
    for sa, sb in spans_outside(x0, x1, gaps):
        mid = (sa + sb) / 2
        for sign in (-1, 1):
            edge_y = y + sign * width / 2
            B["curb"].box((mid, edge_y + sign * CURB_SIGNOFF, CURB_Z),
                          (sb - sa, CURB_WIDTH, CURB_HEIGHT))
            if sidewalk:
                B["sidewalk"].box((mid, edge_y + sign * SIDEWALK_SIGNOFF, SIDEWALK_Z),
                                  (sb - sa, SIDEWALK_WIDTH, SIDEWALK_HEIGHT))


def add_road_v(
    B: dict[str, Batch],
    x: float,
    y0: float = -100,
    y1: float = 100,
    width: float = ROAD_WIDTH,
    sidewalk: bool = True,
    gaps: tuple[tuple[float, float], ...] = (),
) -> None:
    B["asphalt"].box((x, (y0 + y1) / 2, ROAD_Y_OFFSET), (width, y1 - y0, ROAD_HEIGHT))
    for sa, sb in spans_outside(y0, y1, gaps):
        mid = (sa + sb) / 2
        for sign in (-1, 1):
            edge_x = x + sign * width / 2
            B["curb"].box((edge_x + sign * CURB_SIGNOFF, mid, CURB_Z),
                          (CURB_WIDTH, sb - sa, CURB_HEIGHT))
            if sidewalk:
                B["sidewalk"].box((edge_x + sign * SIDEWALK_SIGNOFF, mid, SIDEWALK_Z),
                                  (SIDEWALK_WIDTH, sb - sa, SIDEWALK_HEIGHT))


def add_zebra_h(B: dict[str, Batch], x: float, y: float,
                road_width: float = ROAD_WIDTH, crossing_width: float = ZEBRA_WIDTH) -> None:
    """Zebra che attraversa una strada nord-sud, proporzionata alla corsia."""
    usable = road_width - ZEBRA_MARGIN
    count = max(7, int(round(usable / ZEBRA_STEP)))
    pitch = usable / count
    for i in range(count):
        xx = x - usable / 2 + pitch * (i + 0.5)
        B["road_white"].box((xx, y, ZEBRA_Y),
                            (min(ZEBRA_BAND_MAX, pitch * 0.62), crossing_width, ZEBRA_HEIGHT))


def add_zebra_v(B: dict[str, Batch], x: float, y: float,
                road_width: float = ROAD_WIDTH, crossing_width: float = ZEBRA_WIDTH) -> None:
    """Zebra che attraversa una strada est-ovest, proporzionata alla corsia."""
    usable = road_width - ZEBRA_MARGIN
    count = max(7, int(round(usable / ZEBRA_STEP)))
    pitch = usable / count
    for i in range(count):
        yy = y - usable / 2 + pitch * (i + 0.5)
        B["road_white"].box((x, yy, ZEBRA_Y),
                            (crossing_width, min(ZEBRA_BAND_MAX, pitch * 0.62), ZEBRA_HEIGHT))


def build_accessible_corner(B, ix, iy, sx, sy, vertical_width, horizontal_width,
                            tactile=True):
    """Angolo di marciapiede con invito ribassato e piastra tattile.

    `sx` e `sy` identificano il quadrante. Il vecchio nodo era un cubo piano;
    questa maglia 2 × 2 scende davvero dalla quota del marciapiede a quella
    della carreggiata nell'angolo interno. I cordoli si arrestano ai due lati
    dell'invito invece di chiuderlo con un gradino.
    """
    extent, ramp = 2.25, 1.05
    x_edge = vertical_width / 2
    y_edge = horizontal_width / 2

    def point(u, v, z):
        return (ix + sx * (x_edge + 0.125 + u),
                iy + sy * (y_edge + 0.125 + v), z)

    # Fondo chiuso, poi superficie superiore: 4 cm sul vertice interno e
    # 12 cm sul piano del marciapiede. Le diagonali hanno sempre normale +Z.
    B["sidewalk"].box((ix + sx * (x_edge + 1.25),
                       iy + sy * (y_edge + 1.25), 0.020),
                      (extent, extent, 0.040))
    coords = (0.0, ramp, extent)
    heights = ((0.042, 0.112, 0.120),
               (0.112, 0.120, 0.120),
               (0.120, 0.120, 0.120))

    def face(points):
        if sx * sy < 0:
            points = tuple(reversed(points))
        B["sidewalk"].poly(points)

    for u in range(2):
        for v in range(2):
            p00 = point(coords[u], coords[v], heights[u][v])
            p10 = point(coords[u + 1], coords[v], heights[u + 1][v])
            p11 = point(coords[u + 1], coords[v + 1], heights[u + 1][v + 1])
            p01 = point(coords[u], coords[v + 1], heights[u][v + 1])
            face((p00, p10, p11))
            face((p00, p11, p01))

    # Due cordoli corti, aperti per 1,05 m presso il vertice ribassato.
    curb_length = extent - ramp
    curb_mid = ramp + curb_length / 2
    B["curb"].box((ix + sx * (x_edge + 0.12),
                   iy + sy * (y_edge + 0.125 + curb_mid), 0.078),
                  (0.24, curb_length, 0.156))
    B["curb"].box((ix + sx * (x_edge + 0.125 + curb_mid),
                   iy + sy * (y_edge + 0.12), 0.078),
                  (curb_length, 0.24, 0.156))

    if not tactile:
        return
    # Piastra gialla sul tratto inclinato e quattro bottoni rilevati.
    u0, u1 = 0.48, 0.94
    z0, z1 = 0.083, 0.115
    plate = (point(u0, u0, z0), point(u1, u0, z1),
             point(u1, u1, z1), point(u0, u1, z1))
    if sx * sy < 0:
        plate = tuple(reversed(plate))
    B["road_yellow"].poly(plate)
    for du in (0.60, 0.82):
        for dv in (0.60, 0.82):
            px, py, _ = point(du, dv, 0)
            z = 0.087 + 0.030 * max(du, dv) / ramp
            B["road_yellow"].cylinder((px, py, z + 0.012), 0.045, 0.024, 8)


def build_viale_head(B, sign):
    """Testata di Viale Roma: il piazzale d'arrivo davanti al fondale.

    L'asse maggiore finiva infilandosi sotto Residenza Aurora e Albergo del
    Borgo: la carreggiata e la siepe spartitraffico entravano negli edifici e
    ne riuscivano dal lato opposto. Ora il viale si chiude contro le facciate
    con un piazzale pavimentato: isola centrale alberata, due attraversamenti
    ai lati, aiuole, panchine e lampioni. `sign` +1 = testata nord.
    """
    y_facade = 43.5 * sign            # filo della facciata del fondale
    y0 = y_facade - sign * 7.0        # bordo verso la piazza
    y1 = y_facade + sign * 0.40       # un poco sotto la facciata, per cucire
    mid = (y0 + y1) / 2
    length = abs(y1 - y0)
    # Platea: copre anche gli ultimi metri di carreggiata e marciapiede, così
    # il piazzale non lascia gradini né fessure sul raccordo.
    B["asphalt"].box((0, mid, -0.020), (22.0, length, 0.280))
    B["tile_b"].box((0, y_facade - sign * 1.70, 0.128), (21.0, 2.6, 0.016))
    # Cordolo perimetrale: solo sui fianchi e sulle due estremità del fronte,
    # così l'imbocco centrale resta aperto al passaggio delle auto.
    for sx in (-1, 1):
        B["curb"].box((sx * 7.75, y0 + sign * 0.14, 0.10), (6.50, 0.28, 0.20))
        B["curb"].box((sx * 10.86, mid, 0.10), (0.28, length, 0.20))
    # Isola centrale alberata, in asse con la siepe spartitraffico.
    yc = y_facade - sign * 4.20
    B["curb"].cylinder((0, yc, 0.09), 2.55, 0.24, 32)
    B["grass"].cylinder((0, yc, 0.21), 2.30, 0.10, 32)
    B["bark"].cylinder((0, yc, 1.70), 0.17, 3.00, 12)
    B["leaf"].sphere((0, yc, 4.05), 2.05, (1.0, 0.92, 0.78), 12, 8)
    B["leaf_light"].sphere((0.75, yc + 0.35, 4.75), 1.30, (1.0, 1.0, 0.85), 10, 7)
    for i in range(6):
        a = TAU * i / 6 + 0.3
        B["flower"].sphere((math.cos(a) * 1.75, yc + math.sin(a) * 1.75, 0.34),
                           0.17, (1.0, 0.85, 0.60), 7, 5)
    # Attraversamenti pedonali ai due lati dell'isola.
    for su in (-3.70, 3.70):
        for j in range(5):
            yy = yc - 1.30 + j * 0.62
            B["road_white"].box((su, yy, 0.140), (2.40, 0.44, 0.030))
    # Aiuole, panchine e lampioni: il piazzale è anche un luogo di sosta.
    for sx in (-1, 1):
        ax, ay = sx * 6.60, y_facade - sign * 5.60
        B["curb"].box((ax, ay, 0.10), (3.60, 1.70, 0.20))
        B["grass"].box((ax, ay, 0.20), (3.30, 1.40, 0.10))
        for i in range(4):
            fx = ax - 1.20 + i * 0.80
            B["flower"].sphere((fx, ay, 0.34), 0.17, (1.0, 0.85, 0.60), 7, 5)
            B["leaf_light"].sphere((fx, ay, 0.24), 0.18, (1.0, 1.0, 0.55), 6, 4)
        make_bench(B, sx * 8.90, y_facade - sign * 2.60,
                   -PI / 2 if sx > 0 else PI / 2)
        add_lamp(B, sx * 10.10, y_facade - sign * 1.30, height=5.4, ornate=True)


def build_roads(mats, road_col, plaza_col):
    keys = ("asphalt", "sidewalk", "curb", "road_white", "road_yellow",
            "tile_a", "tile_b", "tile_c", "grass", "leaf", "leaf_light",
            "flower", "cloth_yellow", "cloth_violet", "bark", "concrete",
            "metal", "metal_gold", "lamp", "wood", "wood_light")
    B = make_batch_set(mats, road_col, keys)
    # Rete leggibile: due anelli, quattro assi di quartiere e viale centrale.
    # I vecchi cordoli e marciapiedi erano estrusi da -100 a +100 senza alcuna
    # interruzione: a ogni nodo attraversavano la strada perpendicolare come
    # due passerelle rialzate. Ora ogni asse si arresta sul bordo esatto della
    # strada che incontra; nelle rotatorie il taglio si allarga fino all'anello.
    crossings_x = tuple(sorted((*ROAD_X, 0)))
    crossings_y = ROAD_Y
    roundabouts = ROUNDABOUTS

    def horizontal_gaps(y):
        gaps = []
        for x in crossings_x:
            if (x, y) in roundabouts:
                half = 9.10
            else:
                half = (10.0 if x == 0 else 8.0) / 2 + 0.13
            gaps.append((x - half, x + half))
        return tuple(gaps)

    def vertical_gaps(x, limits=(-100, 100)):
        gaps = []
        for y in crossings_y:
            if not (limits[0] < y < limits[1]):
                continue
            half = 9.10 if (x, y) in roundabouts else 8.0 / 2 + 0.13
            gaps.append((y - half, y + half))
        return tuple(gaps)

    for y in ROAD_Y:
        add_road_h(B, y, -100, 100, 8.0, gaps=horizontal_gaps(y))
    for x in ROAD_X:
        add_road_v(B, x, -100, 100, 8.0, gaps=vertical_gaps(x))
    # Viale Roma: la piazza, il municipio e i due fondali ne spezzano l'asse.
    # La carreggiata non entra più dentro Residenza Aurora e Albergo del Borgo:
    # ogni troncone corre fra due incroci, o fra un incrocio e una testata.
    for y0, y1 in VIALE_SPANS:
        add_road_v(B, 0, y0, y1, 10.0, gaps=vertical_gaps(0, (y0, y1)))
    # Testate del viale: due piazzali d'arrivo davanti ai fondali.
    build_viale_head(B, 1)
    build_viale_head(B, -1)
    # Spartitraffico fiorito lungo i tratti di Viale Roma: un'aiuola
    # rialzata con siepe bassa e fiori a passo regolare divide le corsie,
    # dando al viale principale il carattere di boulevard alberato. Ora si
    # interrompe in corrispondenza degli incroci (prima la siepe attraversava
    # le quattro intersezioni) e delle due testate.
    for y0, y1 in ((-98, -74), (-66, -59), (-43, -36), (-28, -18),
                    (36, 43), (59, 66), (74, 98)):
        mid_y = (y0 + y1) / 2
        length = y1 - y0
        # Cordolo perimetrale dell'aiuola spartitraffico.
        B["curb"].box((0, mid_y, 0.10), (1.2, length, 0.18))
        # Tappeto erboso dentro il cordolo.
        B["grass"].box((0, mid_y, 0.20), (1.0, length - 0.4, 0.10))
        # Siepe bassa continua al centro.
        B["leaf"].box((0, mid_y, 0.52), (0.5, length - 1.0, 0.50))
        # Fiori a passo regolare lungo la siepe, colori alternati.
        flower_keys = ("flower", "cloth_yellow", "cloth_violet", "flower")
        step = 4.5
        n_flowers = max(1, int(length / step))
        for i in range(n_flowers):
            fy = y0 + 1.5 + (y1 - y0 - 3.0) * (i + 0.5) / n_flowers
            key = flower_keys[i % len(flower_keys)]
            B[key].sphere((0, fy, 0.68), 0.18, (1.0, 0.85, 0.6), 7, 5)
            B["leaf_light"].sphere((0.05, fy, 0.50), 0.20, (1.0, 1.0, 0.55), 6, 4)
    # Gli angoli non sono più cubi appoggiati sopra l'asfalto. Ogni quadrante
    # è una superficie propria, raccordata ai quattro tronconi di marciapiede,
    # con il vertice interno abbassato alla quota della carreggiata.
    heads = ((-11.0, 11.0, 36.5, 43.9), (-11.0, 11.0, -43.9, -36.5))

    def in_head(px, py):
        return any(gx0 <= px <= gx1 and gy0 <= py <= gy1
                   for gx0, gx1, gy0, gy1 in heads)

    corner_exists = {}
    for ix in crossings_x:
        for iy in crossings_y:
            if (ix, iy) in roundabouts:
                continue  # qui subentra la rotatoria fiorita
            vertical_width, horizontal_width = (10.0 if ix == 0 else 8.0), 8.0
            B["asphalt"].box((ix, iy, 0.034),
                             (vertical_width, horizontal_width, 0.014))
            for sx in (-1, 1):
                for sy in (-1, 1):
                    px = ix + sx * (vertical_width / 2 + 1.25)
                    py = iy + sy * (horizontal_width / 2 + 1.25)
                    exists = not in_head(px, py)
                    corner_exists[(ix, iy, sx, sy)] = exists
                    if exists:
                        build_accessible_corner(B, ix, iy, sx, sy,
                                                vertical_width, horizontal_width)

    # Attraversamenti accessibili su ogni lato realmente collegato a due
    # angoli. Le zebre precedenti erano centrate nel cuore del nodo e larghe
    # quasi quanto la strada; ora sono fasce da 2,8 m sulle quattro testate e
    # terminano sulle piastre tattili gialle delle rampe. Nei piazzali di
    # testata i lati assorbiti dalla platea vengono omessi automaticamente.
    for ix in crossings_x:
        for iy in crossings_y:
            if (ix, iy) in roundabouts:
                continue
            vertical_width, horizontal_width = (10.0 if ix == 0 else 8.0), 8.0
            yoff = horizontal_width / 2 + 1.35
            xoff = vertical_width / 2 + 1.35
            if all(corner_exists.get((ix, iy, sx, 1), False) for sx in (-1, 1)):
                add_zebra_h(B, ix, iy + yoff, vertical_width)
            if all(corner_exists.get((ix, iy, sx, -1), False) for sx in (-1, 1)):
                add_zebra_h(B, ix, iy - yoff, vertical_width)
            if all(corner_exists.get((ix, iy, 1, sy), False) for sy in (-1, 1)):
                add_zebra_v(B, ix + xoff, iy, horizontal_width)
            if all(corner_exists.get((ix, iy, -1, sy), False) for sy in (-1, 1)):
                add_zebra_v(B, ix - xoff, iy, horizontal_width)
    # Linee di mezzeria discontinue sugli assi principali.
    def in_roundabout(x, y):
        return (x - 23) ** 2 + (y - 32) ** 2 < 100 or \
               (x + 23) ** 2 + (y + 32) ** 2 < 100

    for y in (-70, 70, -32, 32):
        for x in range(-96, 97, 11):
            if y in (-32, 32) and -28 < x < 28:
                continue
            if in_roundabout(x, y):
                continue
            B["road_white"].box((x, y, 0.039), (4.5, 0.13, 0.025))
    for x in (-70, 70, -23, 23, 0):
        if x == 0:
            ranges = [(-98, -18), (30, 98)]
        else:
            ranges = [(-98, 98)]
        for y0, y1 in ranges:
            for y in range(int(y0) + 3, int(y1) - 2, 11):
                if in_roundabout(x, y):
                    continue
                B["road_white"].box((x, y, 0.039), (0.13, 4.5, 0.025))
    # Strisce gialle ai margini della piazza e stalli di sosta.
    for x in (-23, 23):
        B["road_yellow"].box((x, 0, 0.04), (0.12, 16, 0.025))
    # Gli stalli di sosta accanto ai palazzi del viale non sono più quattro
    # strisce isolate sull'erba: li disegna build_parking_lots su due piazzali
    # pavimentati, con fermaruota, isole d'ombra e auto in sosta.
    # Piazza centrale in pietra: cornice, letto e mosaico di lastre.
    make_cube("Basamento della piazza", (0, 0, -0.04), (31.8, 27.8, 0.20),
              mats["curb"], plaza_col, bevel=0.08)
    make_cube("Pavimentazione piazza", (0, 0, 0.08), (30.8, 26.8, 0.16),
              mats["tile_a"], plaza_col, bevel=0.05)
    tile_mats = ("tile_a", "tile_b", "tile_c")
    tile_batches = {k: Batch("Lastre piazza " + k, mats[k], plaza_col)
                    for k in tile_mats}
    for ix, x in enumerate([i * 0.92 - 14.26 for i in range(32)]):
        for iy, y in enumerate([i * 0.92 - 12.42 for i in range(28)]):
            key = tile_mats[(ix + iy + random.randrange(3)) % 3]
            tile_batches[key].box((x, y, 0.185), (0.875, 0.875, 0.055))
    for batch in tile_batches.values():
        batch.flush()
    # Inserti perimetrali e fasce che guidano verso il municipio.
    band = Batch("Fasce decorative in pietra", mats["trim"], plaza_col)
    for x in (-14.7, 14.7):
        band.box((x, 0, 0.23), (0.28, 25.7, 0.06))
    for y in (-12.8, 12.8):
        band.box((0, y, 0.23), (29.5, 0.28, 0.06))
    for x in (-8.4, -7.8, 7.8, 8.4):
        band.box((x, -2.0, 0.24), (0.20, 17.0, 0.05))
    band.flush()
    for batch in B.values():
        batch.flush()
    return B


