    # Panche del sagrato ai lati del portale (`lx = ±3,0`, `ly = -13,5`) con
    # gambe in pietra sul basolato: prima lo scambio degli assi locali le
    # metteva entrambe in asse davanti alla porta (`y = -17,5`) e senza gambe.
