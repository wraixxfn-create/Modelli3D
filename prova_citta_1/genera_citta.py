    clusters = ((-118, 168), (-52, 172), (28, 170), (96, 156), (148, 128),
                (170, 48), (156, -92), (118, -150), (46, -170), (-38, -172),
                (-118, -154), (-170, -72), (-172, 18))
    for ci, (cx, cy) in enumerate(clusters):
        for j in range(9):
            ang = j * 2.39996 + ci * 0.7
            rad = 3.0 + (j % 3) * 2.0
