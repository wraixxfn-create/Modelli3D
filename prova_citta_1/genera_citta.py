            B["bark"].cylinder((x, y, z + 1.5 * s), 0.13 * s, 3.2 * s, 7)
            B["leaf"].sphere((x, y, z + 3.6 * s), 2.0 * s, (1.0, 0.92, 0.78),
                             9, 6)
            B["olive"].sphere((x + 0.9 * s, y + 0.3 * s, z + 4.3 * s),
                              1.35 * s, (1.0, 1.0, 0.85), 8, 6)


