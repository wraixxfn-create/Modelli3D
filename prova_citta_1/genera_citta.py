def _apartment_upper_floors(
    B: dict[str, Batch],
    cx: float, cy: float, yaw: float,
    width: float, depth: float,
    floors: int, modern: bool,
) -> None:
    """Finestre residenziali e balconi dei piani superiori (fronte e retro)."""
    ground_h = 3.45
    upper_h = 2.85
    face_y = -depth / 2
    upper_floors = floors - 1
    cols = 5 if width > 17 else 4
    usable = width - 3.2
    x_positions = [-usable / 2 + usable * (i + 0.5) / cols for i in range(cols)]
    # Fronte principale (-Y): finestre con balconi sfalsati.
    for level in range(upper_floors):
        zc = ground_h + 0.26 + level * upper_h + 1.10
        for col, x in enumerate(x_positions):
            bal = (col + level) % 2 == 0
            add_front_window(B, cx, cy, yaw, x, zc, 1.28, 1.72, depth,
                             balcony=bal, shutter=not modern and col in (0, cols - 1),
                             frame_key="trim")
        # Fascia marcapiano che varia leggermente la luce delle facciate.
        lbox(B["trim"], cx, cy, yaw, 0, face_y - 0.12,
             ground_h + level * upper_h + 0.10,
             width + 0.20, 0.19, 0.13)
    # Retro (+Y) non più cieco: stesse finestre del fronte, con balconi
    # sfalsati di una campata, più porta di servizio e luce al piano terra.
    back_y = depth / 2
    for level in range(upper_floors):
        zc = ground_h + 0.26 + level * upper_h + 1.10
        for col, x in enumerate(x_positions):
            add_front_window(B, cx, cy, yaw, x, zc, 1.28, 1.72, depth,
                             balcony=(col + level) % 2 == 1,
                             shutter=not modern and col in (1, cols - 2),
                             frame_key="trim", side=1)
    lbox(B["wood"], cx, cy, yaw, 0, back_y + 0.07, 1.55, 0.95, 0.12, 2.2)
    lbox(B["trim"], cx, cy, yaw, 0, back_y + 0.10, 2.78, 1.25, 0.16, 0.14)
    lbox(B["concrete"], cx, cy, yaw, 0, back_y + 0.55, 0.16, 1.7, 1.1, 0.18)
    lbox(B["lamp"], cx, cy, yaw, 0.85, back_y + 0.16, 2.95, 0.19, 0.08, 0.30)


def _apartment_side_windows(
    B: dict[str, Batch],
    cx: float, cy: float, yaw: float,
    width: float, depth: float, floors: int,
) -> None:
    """Finestre sui fianchi visibili: vetro, cornice e davanzale.

    Le due colonne centrali cadevano dentro il corpo scala vetrato, che
    occupa la fascia centrale di ogni fianco (2,60 m di vetro, da -0,02 ×
    profondità - 1,30 a -0,02 × profondità + 1,30): con le profondità in uso
    la compenetrazione arrivava a 64 cm e la vetrata del vano copriva la
    finestra su tutta l'altezza (1,62 m). Ora ogni colonna sta fuori dal vano,
    a 10 cm dal suo bordo, e le quattro colonne restano quattro.
    """
    ground_h = 3.45
    upper_h = 2.85
    side_x = width / 2
    upper_floors = floors - 1
    # Il traverso di piano del vano è largo 2,90 m (semiampiezza 1,45) e la
    # cornice di ogni finestra sporge di 0,73 m: la colonna interna sta a
    # 2,30 m dall'asse, con 12 cm fra traverso e cornice e 25 cm fra traverso
    # e vetrata lunga l'intero fianco. La colonna esterna resta dove era, a
    # 0,33 × profondità.
    inner_y = 2.30
    for sign in (-1, 1):
        for level in range(upper_floors):
            zc = ground_h + 0.25 + level * upper_h + 1.1
            for y in (-depth * 0.33, -inner_y, inner_y, depth * 0.33):
                lbox(B["glass"], cx, cy, yaw, sign * (side_x + 0.055), y, zc,
                     0.12, 1.20, 1.62)
                for edge in (-1, 1):
                    lbox(B["trim"], cx, cy, yaw,
                         sign * (side_x + 0.14), y + edge * 0.67, zc,
                         0.16, 0.12, 1.78)
                lbox(B["trim"], cx, cy, yaw, sign * (side_x + 0.14), y,
                     zc - 0.90, 0.16, 1.46, 0.12)


